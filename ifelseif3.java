public class ifelseif3 {
    public static void main(String args[]){
        char c='z';
        if (c=='a') {
            System.out.println("Very Good");
        }
        else if(c=='b'){
            System.out.println("Good");
        }
        else if(c=='c'){
            System.out.println("Average");
        }
        else if(c=='d'){
            System.out.println("Poor");
        }
        else{
            System.out.println("Invalid Grade");
        }
    }
    
}
